# COVID-19 Global Health & Vaccination Data Analysis

## Project Overview

This project uses PostgreSQL to analyze global COVID-19 health, mortality, hospitalization, ICU, and vaccination data. The analysis includes data quality checks, data cleaning, and SQL queries to identify trends and country-level insights.

## Tools & Technologies

- PostgreSQL
- SQL
- Aggregate Functions
- GROUP BY & ORDER BY
- WHERE & Filtering
- Type Casting
- ROUND()
- NULL Data Auditing
- Data Cleaning

## Dataset

The project uses two datasets:

- `covid_deaths`
- `covid_vaccinations`

## Key Analysis

The project answers questions related to:

1. COVID-19 death percentage in India
2. Deaths as a percentage of population
3. Validation of death and population data
4. Countries with the highest death percentage
5. COVID-19 cases as a percentage of India's population
6. Worldwide COVID-19 case percentage
7. Total COVID-19 cases by continent
8. Total COVID-19 deaths by continent
9. Daily cases, hospitalization, and ICU trends in India
10. Population aged 65+ by country
11. Total vaccinated people by country

